int main(int argc, char ** argv) {
  const char * out = std::getenv("GDEFSSQLITE_WRITE_CORPUS");
  if (out != nullptr && out[0] != '\0') {
    return WriteCorpus(out);
  }
  ::testing::InitGoogleTest(&argc, argv);
  return RUN_ALL_TESTS();
}
