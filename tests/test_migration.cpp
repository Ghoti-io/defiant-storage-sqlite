/**
 * @file
 *
 * The migration corpus gate. The SQL layout is at version 1, and version 1
 * is final (AD-34): every later layout is a recorded step from it, taken on
 * stores that already hold data. tests/corpus/schema_1.sql is such a store,
 * written by this layout and committed as SQL text: the snapshot fixture's
 * tenant (two types, groups, multiples, a personal field with blind rows, a
 * retired field, two languages, drafts, records, counters, the outbox). The
 * gate opens it as it is and requires every row back, then takes steps on it
 * (fields added to both types, a group gaining a column, a new type with a
 * blind table, indexes built) and requires that no row it held was lost.
 *
 * GDEFSSQLITE_WRITE_CORPUS=<dir> writes the corpus there instead of running
 * the tests (schema_1.sql, schema_1.truth, schema_1.current); it is made
 * once, by this layout, and never regenerated by a later one.
 */

